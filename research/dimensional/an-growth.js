function binomial(n, k) {
  if (!Number.isInteger(n) || !Number.isInteger(k) || k < 0 || k > n) return 0;
  const r = Math.min(k, n - k);
  let value = 1;
  for (let i = 1; i <= r; i += 1) value = (value * (n - r + i)) / i;
  return Math.round(value);
}

function factorial(n) {
  if (!Number.isInteger(n) || n < 0) throw new Error('factorial requires integer n >= 0.');
  let value = 1;
  for (let i = 2; i <= n; i += 1) value *= i;
  return value;
}

function positiveCompositionCount(total, parts) {
  if (!Number.isInteger(total) || !Number.isInteger(parts) || total < 1 || parts < 1) return 0;
  return binomial(total - 1, parts - 1);
}

/**
 * Graph distance in the A_n root lattice generated by roots e_i-e_j equals
 * the total positive mass of an integer zero-sum coordinate vector.
 *
 * Count exact-distance-m vectors by choosing p positive and q negative
 * coordinates, distributing m positive units among p slots and m negative
 * units among q slots, with remaining coordinates zero.
 */
export function anShellCount(n, m) {
  if (!Number.isInteger(n) || n < 1) throw new Error('A_n requires integer n >= 1.');
  if (!Number.isInteger(m) || m < 0) throw new Error('Shell radius requires integer m >= 0.');
  if (m === 0) return 1;

  const coordinates = n + 1;
  let count = 0;
  for (let p = 1; p <= Math.min(m, coordinates - 1); p += 1) {
    for (let q = 1; q <= Math.min(m, coordinates - p); q += 1) {
      const chooseSigns = binomial(coordinates, p) * binomial(coordinates - p, q);
      const distributePositive = positiveCompositionCount(m, p);
      const distributeNegative = positiveCompositionCount(m, q);
      count += chooseSigns * distributePositive * distributeNegative;
    }
  }
  return count;
}

/**
 * Independent coefficient extraction from the established A_n coordination
 * generating function (Conway-Sloane / Bacher-de la Harpe-Venkov):
 *
 *   G_n(z) = [sum_{j=0}^n C(n,j)^2 z^j] / (1-z)^n.
 *
 * Coefficient of z^m in (1-z)^(-n) is C(n+m-1,n-1).
 */
export function anShellCountFromGeneratingFunction(n, m) {
  if (!Number.isInteger(n) || n < 1) throw new Error('A_n requires integer n >= 1.');
  if (!Number.isInteger(m) || m < 0) throw new Error('Shell radius requires integer m >= 0.');

  let coefficient = 0;
  for (let j = 0; j <= Math.min(n, m); j += 1) {
    coefficient += (binomial(n, j) ** 2) * binomial(n + (m - j) - 1, n - 1);
  }
  return coefficient;
}

export function anBallCount(n, radius) {
  if (!Number.isInteger(radius) || radius < 0) throw new Error('Ball radius requires integer radius >= 0.');
  let count = 0;
  for (let m = 0; m <= radius; m += 1) count += anShellCount(n, m);
  return count;
}

export function anGrowthAsymptotic(n) {
  if (!Number.isInteger(n) || n < 1) throw new Error('A_n requires integer n >= 1.');
  const vandermondeNumeratorAtOne = binomial(2 * n, n);
  return {
    n,
    numeratorAtOne: vandermondeNumeratorAtOne,
    shellLeadingCoefficient: vandermondeNumeratorAtOne / factorial(n - 1),
    ballLeadingCoefficient: vandermondeNumeratorAtOne / factorial(n),
    shellDegree: n - 1,
    ballDegree: n,
    asymptoticFrontierToFieldFactor: n,
    relation: 'shell/ball ~ n/radius',
  };
}

export function frontierToFieldRatio(n, radius) {
  if (!Number.isInteger(radius) || radius < 1) throw new Error('Frontier ratio requires integer radius >= 1.');
  return anShellCount(n, radius) / anBallCount(n, radius);
}

export function a2ClosedFormShell(radius) {
  if (!Number.isInteger(radius) || radius < 0) throw new Error('Radius requires integer >= 0.');
  return radius === 0 ? 1 : 6 * radius;
}

export function a2ClosedFormBall(radius) {
  if (!Number.isInteger(radius) || radius < 0) throw new Error('Radius requires integer >= 0.');
  return 1 + 3 * radius * (radius + 1);
}

export function dimensionalGrowthTable({ maxDimension = 6, maxRadius = 5 } = {}) {
  const rows = [];
  for (let n = 1; n <= maxDimension; n += 1) {
    for (let radius = 0; radius <= maxRadius; radius += 1) {
      rows.push({
        n,
        radius,
        shellCount: anShellCount(n, radius),
        shellCountKnownGeneratingFunction: anShellCountFromGeneratingFunction(n, radius),
        ballCount: anBallCount(n, radius),
        frontierToFieldRatio: radius > 0 ? frontierToFieldRatio(n, radius) : null,
      });
    }
  }
  return rows;
}

